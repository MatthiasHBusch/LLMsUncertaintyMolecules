"""
Markdown results report of the ICL main run from results/icl/cells.csv (src/analyze_icl.py) and
the classical baselines (results/baselines/summary.csv).

    python src/report_icl.py                 # -> docs/RESULTS_ICL_R1.md
    python src/report_icl.py --reasoning low --out docs/RESULTS_ICL_R1.md
    python src/report_icl.py --draws         # -> docs/RESULTS_DRAWS.md + results/icl/draws_cells.csv

The default and --ladder reports use context draw 1 only (the main split; cells.csv rows with
draw == 1, baseline rows with seed == 0 and draw == 1), so they are unchanged by the additional
context draws. --draws compares the context draws 1-3 at N = 30 / 60 / 120 (see draws_report).
"""
import argparse
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(__file__))
from common import DATASET_KEYS, ROOT  # noqa: E402
from selective_prediction import rmse_most_certain  # noqa: E402  (tie-aware; also writes selective_prediction.csv)

PRETTY = {"haiku55": "Haiku 5.5", "sonnet55": "Sonnet 5.5", "gpt6luna": "GPT-6 Luna", "gpt61sol": "GPT-6.1 Sol",
          "gem38flash": "Gemini 3.8 Flash", "glm53flash": "GLM 5.3 Flash", "gpt6astra": "GPT-6 Astra",
          "tabpfn": "TabPFN v3.5", "rf_desc": "RF (descriptors)", "rf": "RF (Morgan)", "trivial": "trivial",
          "gp_tanimoto": "GP (Tanimoto)", "mlp_ens": "MLP ensemble", "chemprop_ens": "Chemprop ensemble",
          "knn_tanimoto": "kNN (Tanimoto)"}
ORDER = ["sonnet55", "haiku55", "gpt61sol", "gpt6luna", "gpt6astra", "gem38flash", "glm53flash"]
BASE_ORDER = ["tabpfn", "gp_tanimoto", "chemprop_ens", "mlp_ens", "rf_desc", "rf", "knn_tanimoto", "trivial"]


def pivot_md(df, value, index="model", fmt="{:.2f}", order=None):
    p = df.pivot_table(index=index, columns="size", values=value, aggfunc="first")
    if order:
        p = p.reindex([o for o in order if o in p.index])
    cols = list(p.columns)
    lines = ["| " + index + " | " + " | ".join(f"N={c}" for c in cols) + " |",
             "|---|" + "---|" * len(cols)]
    for idx, row in p.iterrows():
        vals = [("" if pd.isna(v) else fmt.format(v)) for v in row.values]
        lines.append(f"| {PRETTY.get(idx, idx)} | " + " | ".join(vals) + " |")
    return "\n".join(lines)


LEVELS = ["none", "minimal", "low", "medium", "high"]


def ladder_report(C, out_path):
    """Reasoning ladder: per dataset x model a table with one row per effort level and the
    min / max context size side by side (RMSE, PICP68, rho(UC1,|err|), NLL, median reasoning
    tokens, cost). Only the min and max sizes of the main run are used; `low` rows come from
    the main run (repeat 0 only would be ideal, but cells.csv pools repeats -- noted in the doc)."""
    rows = []
    out = ["# Reasoning ladder: results (R = 3 per level since the 2026-10-12/13 extension; `low` from the main run)", "",
           "Generated by `src/report_icl.py --ladder` from `results/icl/cells.csv`. Effort levels requested "
           "via OpenRouter `reasoning.effort`; `none` is rejected (HTTP 400) by Sonnet 5.5, GPT-6.1 Sol, "
           "Gemini 3.8 Flash and GLM 5.3 Flash, so those rows are absent. The `low` rows are the main-run "
           "cells; every level pools R = 3 repeats (450 calls per cell). Columns: value at the "
           "smallest context (N = 30) / at the largest (1000, antiviral 844, ESOL 976). `n_mol` is the number of "
           "test molecules with a parsable answer; `trunc` the share of calls cut at the completion cap "
           "(ICL_MAX_TOKENS = 32000). Gemini 3.8 Flash `high` loses 15-35 % of the calls (top rung 28-35 %) to truncation on the "
           "three clean sets (~30k reasoning tokens), so its `high` rows are a censored subset of the test set.", ""]
    for ds in DATASET_KEYS:
        d = C[C.dataset == ds]
        if d.empty:
            continue
        nmin, nmax = int(d["size"].min()), int(d["size"].max())
        out += [f"## {ds} (N = {nmin} / {nmax})", ""]
        for m in ORDER:
            dm = d[(d.model == m) & d["size"].isin([nmin, nmax])]
            if dm.empty:
                continue
            out += [f"**{PRETTY.get(m, m)}**", "",
                    "| effort | RMSE | Spearman | PICP68 | PICP90 | rho(UC1,err) | NLL | reasoning tok (median) | completion tok (median) | $ / cell | n_mol | trunc |",
                    "|---|---|---|---|---|---|---|---|---|---|---|---|"]
            for lv in LEVELS:
                a = dm[(dm.reasoning == lv) & (dm["size"] == nmin)]
                b = dm[(dm.reasoning == lv) & (dm["size"] == nmax)]
                if a.empty and b.empty:
                    continue
                def pair(col, fmt="{:.2f}"):
                    va = fmt.format(a[col].iloc[0]) if not a.empty and pd.notna(a[col].iloc[0]) else "-"
                    vb = fmt.format(b[col].iloc[0]) if not b.empty and pd.notna(b[col].iloc[0]) else "-"
                    return f"{va} / {vb}"
                out.append(f"| {lv} | {pair('RMSE')} | {pair('spearman_pred')} | {pair('PICP68')} | {pair('PICP90')} | "
                           f"{pair('rho_UC1_err')} | {pair('NLL')} | {pair('median_reasoning_tokens', '{:.0f}')} | "
                           f"{pair('median_completion_tokens', '{:.0f}')} | {pair('cost_usd')} | {pair('n_mol', '{:.0f}')} | {pair('trunc_rate')} |")
                for sz, cell in ((nmin, a), (nmax, b)):
                    if not cell.empty:
                        rows.append(dict(dataset=ds, model=m, size=sz, effort=lv, **{k: cell[k].iloc[0] for k in
                                    ["RMSE", "spearman_pred", "PICP68", "PICP90", "rho_UC1_err", "NLL",
                                     "median_reasoning_tokens", "median_completion_tokens", "cost_usd", "n_mol", "trunc_rate", "parse_rate"]}))
            out.append("")
    with open(out_path, "w", encoding="utf8") as f:
        f.write("\n".join(out))
    pd.DataFrame(rows).to_csv(os.path.join(ROOT, "results", "icl", "ladder_cells.csv"), index=False)
    print("->", out_path)


DRAW_SIZES = [30, 60, 120]
DRAW_ORDER = ["sonnet55", "haiku55", "gpt61sol", "gpt6luna", "gpt6astra", "gem38flash", "glm53flash"]
DRAW_BASE = ["tabpfn", "gp_tanimoto", "chemprop_ens", "mlp_ens", "rf_desc"]
DRAW_PRETTY = {**PRETTY, "gpt6astra": "GPT-6 Astra"}
MIN_COVERAGE = 0.95     # LLM cells with fewer answered molecules (e.g. a run in progress) are left out
DRAW_METRICS = [("RMSE", "RMSE"), ("spearman_pred", "Spearman(truth, prediction)"),
                ("rho_UC1_err", "rho(UC1, |err|) (baselines: their sigma)"),
                ("PICP68", "PICP68 (nominal 0.68)"),
                ("RMSE50", "RMSE of the 50 % most certain molecules by UC1 (baselines: by sigma), "
                           "random tie-breaking, sqrt of the expected MSE")]


def draws_report(reasoning, out_path):
    """Context draws: per dataset x model x N in {30, 60, 120} the metrics of every context draw
    (1 = main split, 2 / 3 = data/splits/<ds>_v2_draw<d>.json), their mean and SD over the draws
    present (SD with ddof = 1, only when >= 2 draws), for the LLM panel (reasoning `reasoning`) and
    the baselines of DRAW_BASE (seed 0; only if summary.csv has a `draw` column). RMSE50 comes from
    selective_prediction.rmse_most_certain (exact sqrt of the expected MSE over random tie-breaking), the same
    function that writes results/icl/selective_prediction.csv."""
    icl = os.path.join(ROOT, "results", "icl")
    C = pd.read_csv(os.path.join(icl, "cells.csv"))
    if "draw" not in C.columns:
        C["draw"] = 1
    C = C[(C.reasoning == reasoning) & C["size"].isin(DRAW_SIZES)].copy()
    # cells of a run still in progress (or with mass refusals) would distort mean / SD: listed, not used
    incomplete = C[C.coverage < MIN_COVERAGE]
    C = C[C.coverage >= MIN_COVERAGE]
    rows = []
    for ds in DATASET_KEYS:                      # RMSE50 from the per-molecule tables
        pm = os.path.join(icl, f"{ds}_permolecule.csv")
        if not os.path.exists(pm):
            continue
        P = pd.read_csv(pm, dtype={"mol_id": str})
        if "draw" not in P.columns:
            P["draw"] = 1
        P = P[(P.reasoning == reasoning) & P["size"].isin(DRAW_SIZES)]
        for (m, n, d), g in P.groupby(["model", "size", "draw"], sort=False):
            c = C[(C.dataset == ds) & (C.model == m) & (C["size"] == n) & (C.draw == d)]
            if c.empty:
                continue
            c = c.iloc[0]
            rows.append(dict(dataset=ds, model=m, family="LLM", size=int(n), draw=int(d), n_mol=int(c.n_mol),
                             n_calls=int(c.n_calls), RMSE=c.RMSE, spearman_pred=c.spearman_pred,
                             rho_UC1_err=c.rho_UC1_err, PICP68=c.PICP68,
                             RMSE50=rmse_most_certain(g.pred - g.truth, g.uc1)))
    B = pd.read_csv(os.path.join(ROOT, "results", "baselines", "summary.csv"))
    has_base_draws = "draw" in B.columns
    if has_base_draws:
        B = B[(B.seed == 0) & B.method.isin(DRAW_BASE) & B["size"].isin(DRAW_SIZES)]
        for _, b in B.iterrows():
            d = int(b.draw)
            stem = f"{b.method}__{b.dataset}__N{int(b['size'])}" + ("" if d == 1 else f"__d{d}")
            D = pd.read_csv(os.path.join(ROOT, "results", "baselines", stem + ".csv"))
            rows.append(dict(dataset=b.dataset, model=b.method, family="baseline", size=int(b["size"]), draw=d,
                             n_mol=int(b.n_mol), n_calls=np.nan, RMSE=b.RMSE, spearman_pred=b.spearman_pred,
                             rho_UC1_err=b.rho_UC1_err, PICP68=b.PICP68,
                             RMSE50=rmse_most_certain(D.prediction - D.truth, D.uncertainty)))
    L = pd.DataFrame(rows)
    L.to_csv(os.path.join(icl, "draws_cells.csv"), index=False)
    draws = sorted(L.draw.unique())
    order = [m for m in DRAW_ORDER + DRAW_BASE if m in set(L.model)]

    def agg(g, col):
        v = g.set_index("draw")[col]
        return v, v.mean(), (v.std(ddof=1) if len(v) >= 2 else np.nan)

    present = L[L.family == "LLM"].groupby("model").draw.apply(lambda x: sorted(set(x)))
    out = [f"# Context draws: results at N = 30 / 60 / 120 (reasoning `{reasoning}`)", "",
           "Generated by `src/report_icl.py --draws` from `results/icl/cells.csv`, `results/icl/<ds>_permolecule.csv` "
           "and `results/baselines/summary.csv` (long table: `results/icl/draws_cells.csv`). Draw 1 = the main split "
           "(`data/splits/<ds>_v2.json`), draws 2 and 3 = independent nested permutations of the same deduplicated "
           "training pool (`data/splits/<ds>_v2_draw<d>.json`, `src/make_splits.py --draws 3`); the test set (150 "
           "molecules) is the same in every draw. Mean and SD (ddof = 1) are over the draws present; SD needs >= 2. "
           "RMSE50 = RMSE of the 50 % of test molecules with the smallest UC1 (baselines: smallest sigma), "
           "with equal sigmas at the cut broken uniformly at random, exact square root of the expected MSE "
           "(`src/selective_prediction.py`, since 2026-10-14; "
           "same values as `results/icl/selective_prediction.csv`). LLM cells pool the repeats of a cell (R = 3: prediction and UC1 "
           "are means over the parsed repeats).", "",
           "Draws present per LLM: " + "; ".join(f"{DRAW_PRETTY.get(m, m)} {v}" for m, v in present.items()) + ". "
           + ("Baselines: " + " / ".join(m for m in DRAW_BASE if m in set(L.model)) + ", seed 0." if has_base_draws else
              "Baselines: summary.csv has no `draw` column yet (run `src/baselines/analyze_baselines.py`).")
           + (" Left out (coverage < %.2f, e.g. a run still in progress): " % MIN_COVERAGE
              + ", ".join(f"{r.dataset}/{r.model}/N{int(r['size'])}/d{int(r.draw)} ({int(r.n_mol)} molecules)"
                          for _, r in incomplete.iterrows()) + "." if len(incomplete) else ""), ""]
    # learning-curve inversions: RMSE(60) > RMSE(30) per draw and on the draw mean
    out += ["## Learning-curve inversions (RMSE at N = 60 > RMSE at N = 30), LLMs", "",
            "| dataset | " + " | ".join(f"draw {d}" for d in draws) + " | mean over draws |",
            "|---|" + "---|" * (len(draws) + 1)]
    for ds in DATASET_KEYS:
        d0 = L[(L.dataset == ds) & (L.family == "LLM")]
        cells = []
        for d in draws:
            p = d0[d0.draw == d].pivot_table(index="model", columns="size", values="RMSE")
            if 30 in p.columns and 60 in p.columns:
                ok = p[[30, 60]].dropna()
                cells.append(f"{int((ok[60] > ok[30]).sum())} of {len(ok)}")
            else:
                cells.append("-")
        pm = d0.groupby(["model", "size"]).RMSE.mean().unstack()
        if 30 in pm.columns and 60 in pm.columns:
            ok = pm[[30, 60]].dropna()
            cells.append(f"{int((ok[60] > ok[30]).sum())} of {len(ok)}")
        else:
            cells.append("-")
        out.append(f"| {ds} | " + " | ".join(cells) + " |")
    out.append("")
    for ds in DATASET_KEYS:
        d0 = L[L.dataset == ds]
        if d0.empty:
            continue
        out += [f"## {ds}", ""]
        for col, title in DRAW_METRICS:
            out += [f"**{title}**", "",
                    "| model | N | " + " | ".join(f"d{d}" for d in draws) + " | mean | SD |",
                    "|---|---|" + "---|" * (len(draws) + 2)]
            for m in order:
                for n in DRAW_SIZES:
                    g = d0[(d0.model == m) & (d0["size"] == n)]
                    if g.empty:
                        continue
                    v, mu, sd = agg(g, col)
                    vals = [("" if d not in v.index or pd.isna(v[d]) else f"{v[d]:.2f}") for d in draws]
                    out.append(f"| {DRAW_PRETTY.get(m, m)} | {n} | " + " | ".join(vals) +
                               f" | {mu:.2f} | {'' if pd.isna(sd) else f'{sd:.2f}'} |")
            out.append("")
    with open(out_path, "w", encoding="utf8") as f:
        f.write("\n".join(out))
    print("->", out_path, "  rows:", len(L), " draws:", draws)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--reasoning", default="low")
    ap.add_argument("--out", default=os.path.join(ROOT, "docs", "RESULTS_ICL_R1.md"))
    ap.add_argument("--ladder", action="store_true", help="write the reasoning-ladder report instead")
    ap.add_argument("--draws", action="store_true",
                    help="write the context-draw comparison (docs/RESULTS_DRAWS.md) instead")
    ap.add_argument("--ladder-out", default=os.path.join(ROOT, "docs", "RESULTS_LADDER_R1.md"))
    ap.add_argument("--draws-out", default=os.path.join(ROOT, "docs", "RESULTS_DRAWS.md"))
    a = ap.parse_args()
    if a.draws:
        draws_report(a.reasoning, a.draws_out)
        return
    C = pd.read_csv(os.path.join(ROOT, "results", "icl", "cells.csv"))
    if "draw" in C.columns:
        C = C[C.draw == 1].drop(columns="draw")          # main split only (context draws: --draws)
    if a.ladder:
        ladder_report(C, a.ladder_out)
        return
    C = C[C.reasoning == a.reasoning]
    B = pd.read_csv(os.path.join(ROOT, "results", "baselines", "summary.csv"))
    if "seed" in B.columns:
        B = B[B.seed == 0]
    if "draw" in B.columns:
        B = B[B.draw == 1]
    B = B.rename(columns={"method": "model"})
    n_rep = int(C.n_calls.sum() / max(C.n_mol.sum(), 1) + 0.5)

    out = [f"# ICL main run: results (reasoning `{a.reasoning}`, R = {n_rep})", "",
           f"Generated by `src/report_icl.py` from `results/icl/cells.csv` ({len(C)} cells, "
           f"{int(C.n_calls.sum())} calls, ${C.cost_usd.sum():.2f}) and `results/baselines/summary.csv`. "
           "Metrics per cell over the 150 test molecules (fewer where the provider refused calls, see the "
           "n_mol table): RMSE and Spearman(truth, prediction) for accuracy; PICP68 = share of test molecules "
           "whose truth lies within prediction +/- 1.0 x the self-reported sigma (nominal 0.6827 for a Gaussian), "
           "PICP90 within 1.645 sigma (nominal 0.90); rho(UC1, |err|) = "
           "Spearman between the self-reported sigma and the absolute error; NLL of N(prediction, sigma^2).", ""]
    out += ["## Coverage of the cells", "",
            f"Parse rate of the stored records min {C.parse_rate.min():.3f}, truncation max {C.trunc_rate.max():.3f}, "
            f"coverage (answered molecules / 150) min {C.coverage.min():.3f}. Cells with fewer than "
            "150 molecules (provider-side refusals of individual prompts; the calls were not rephrased):", ""]
    short = C[C.n_mol < 150]
    if len(short):
        out.append(short[["dataset", "model", "size", "n_mol"]].to_markdown(index=False))
    else:
        out.append("none")
    out.append("")
    out += ["## Cost per model (USD)", "", C.groupby("model").cost_usd.sum().round(2).rename(index=PRETTY).to_markdown(), ""]

    for ds in DATASET_KEYS:
        d = C[C.dataset == ds]
        b = B[B.dataset == ds]
        out += [f"## {ds}", ""]
        out += ["**RMSE (LLMs)**", "", pivot_md(d, "RMSE", order=ORDER), ""]
        out += ["**RMSE (classical baselines, same cells)**", "", pivot_md(b, "RMSE", order=BASE_ORDER), ""]
        out += ["**Spearman(truth, prediction)**", "", pivot_md(d, "spearman_pred", order=ORDER), ""]
        out += ["**PICP68 (nominal 0.68)**", "", pivot_md(d, "PICP68", order=ORDER), ""]
        out += ["**PICP90 (nominal 0.90)**", "", pivot_md(d, "PICP90", order=ORDER), ""]
        out += ["**rho(UC1, |err|)**", "", pivot_md(d, "rho_UC1_err", order=ORDER), ""]
        if "rho_UC1_err" in b.columns:
            out += ["**rho(sigma, |err|) of the baselines**", "", pivot_md(b, "rho_UC1_err", order=BASE_ORDER), ""]
        out += ["**NLL**", "", pivot_md(d, "NLL", order=ORDER), ""]
        out += ["**Median reasoning tokens**", "", pivot_md(d, "median_reasoning_tokens", fmt="{:.0f}", order=ORDER), ""]
        if ds == "esol" and "RMSE_never_recalled" in d.columns:
            nnr = int(d.n_never_recalled.dropna().iloc[0]) if d.n_never_recalled.notna().any() else 0
            nrc = int(d.n_recalled.iloc[0]) if "n_recalled" in d.columns else 0
            nun = int(d.n_unscorable_zeroshot.iloc[0]) if "n_unscorable_zeroshot" in d.columns else 0
            out += [f"**RMSE on the recalled subset** ({nrc} molecules reproduced to 3 significant figures by at "
                    "least one panel model in the zero-shot check)", "", pivot_md(d, "RMSE_recalled", order=ORDER), "",
                    f"**RMSE on the never-recalled, scorable subset** ({nnr} molecules with >= 3-figure labels that no "
                    f"panel model reproduced; the {nun} molecules with < 3-figure labels are unscorable and excluded "
                    "from both subsets)", "", pivot_md(d, "RMSE_never_recalled", order=ORDER), "",
                    "**PICP68 recalled / never-recalled**", "", pivot_md(d, "PICP68_recalled", order=ORDER), "",
                    pivot_md(d, "PICP68_never_recalled", order=ORDER), ""]
    with open(a.out, "w", encoding="utf8") as f:
        f.write("\n".join(out))
    print("->", a.out)


if __name__ == "__main__":
    main()
